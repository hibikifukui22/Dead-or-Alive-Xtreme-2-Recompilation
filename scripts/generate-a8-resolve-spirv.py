"""Generate scoped RGBA8->A8 SPIR-V variants of the Vulkan 8bpp resolve shader.

The Vulkan counterpart of generate-a8-resolve.py (DXBC). Xbox D3D encodes A8
as k_8 + LOW_BLUE; for RGBA8 sources that must select alpha, but the resolve
shader selects blue (shift 16) for swapped k_8 destinations. DOAX2's shadow
blur writes only alpha, so copying blue gives zero shadows and black frames.
Changes the four `OpSelect %uint swap %uint_16 %uint_0` component shifts (one
per MSAA sample path) to 24, preserving everything else. The runtime selects
these variants only for RGBA8 -> k_8 LOW_BLUE resolves.
Reference: https://github.com/xenia-canary/xenia-canary/pull/1142
"""
from pathlib import Path
import re
import struct

root = Path(__file__).resolve().parent.parent
folder = root / 'sdk/rexglue-sdk/src/graphics/shaders/vulkan_spirv'
OP_TYPE_INT, OP_CONSTANT, OP_SELECT = 21, 43, 169

for suffix in ('', '_scaled'):
    source = folder / f'resolve_full_8bpp{suffix}_cs.h'
    text = source.read_text()
    values = text.split('[] = {', 1)[1].split('}', 1)[0]
    words = [int(v, 16) for v in re.findall(r'0x[0-9A-Fa-f]+', values)]
    assert words[0] == 0x07230203, 'not SPIR-V'
    uint_types, constants = set(), {}
    pos = 5
    instructions = []
    while pos < len(words):
        count, opcode = words[pos] >> 16, words[pos] & 0xFFFF
        assert count
        instructions.append((pos, opcode, count))
        if opcode == OP_TYPE_INT and words[pos + 2] == 32 and words[pos + 3] == 0:
            uint_types.add(words[pos + 1])
        elif opcode == OP_CONSTANT and words[pos + 1] in uint_types and count == 4:
            constants[words[pos + 3]] = words[pos + 2]
        pos += count
    uint_16, uint_24, uint_0 = constants[16], constants[24], constants[0]
    patched = 0
    for pos, opcode, count in instructions:
        if (opcode == OP_SELECT and count == 6 and words[pos + 1] in uint_types and
                words[pos + 4] == uint_16 and words[pos + 5] == uint_0):
            words[pos + 4] = uint_24
            patched += 1
    assert patched == 4, (source, patched)
    name = f'resolve_rgba8_to_a8{suffix}_cs'
    rows = ['    ' + ', '.join('0x%08X' % w for w in words[i:i + 8]) + ','
            for i in range(0, len(words), 8)]
    (folder / (name + '.h')).write_text(
        '// Generated by scripts/generate-a8-resolve-spirv.py; RGBA8 to A8 only.\n'
        'const uint32_t ' + name + '[] = {\n' + '\n'.join(rows) + '\n};\n')
    print(name, patched, 'component selections corrected')
